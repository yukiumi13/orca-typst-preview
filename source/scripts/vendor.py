"""Extract the bundled Tinymist frontend and adapt its transport/lifecycle entry."""
import hashlib
from pathlib import Path
import re
import sys

source = Path(sys.argv[1]).read_text()
root = Path(__file__).resolve().parents[1]
scripts = re.findall(r'<script[^>]*>(.*?)</script>', source, re.S)
script = scripts[1]
old = 'const { nextWs } = buildWs();\n  window.onload = () => nextWs(wsArgs);\n  setupVscodeChannel(nextWs);'
assert script.count(old) == 1, 'Tinymist lifecycle changed; inspect upstream before updating.'
script = script.replace(old, 'const { nextWs, stop } = buildWs();\n  window.startTypstPreview = () => nextWs(wsArgs);\n  window.stopTypstPreview = stop;')
old = 'return { nextWs };'
assert script.count(old) == 1
script = script.replace(old, 'return { nextWs, stop: () => { const previous = previousDispose; previousDispose = Promise.resolve(() => {}); return previous.then((dispose) => dispose()); } };')
script = script.replace('url: urlObject.href, previewMode', 'url: "ws://preview.invalid/", previewMode')
(root / 'vendor/tinymist.js').write_text('// Tinymist bundled preview frontend. See NOTICE.md and LICENSE-tinymist.\n' + script)
styles = '\n'.join(re.findall(r'<style[^>]*>(.*?)</style>', source, re.S))
(root / 'vendor/tinymist.css').write_text(styles)
body = re.search(r'<body>(.*?)</body>', source, re.S).group(1)
(root / 'editor/index.html').write_text('''<!doctype html>
<html><head><meta charset="utf-8"><title>Typst Preview</title>
<link rel="stylesheet" href="../vendor/tinymist.css"><link rel="stylesheet" href="style.css"></head>
<body><header id="toolbar"><span id="workspace"></span><span id="filename">Typst</span><span id="status" role="status">Opening…</span>
<span id="pdf-status" role="status"></span><button id="reveal" title="Show the source cursor in the preview">Reveal cursor</button><button id="toggle">Preview</button></header>
<pre id="problem" role="alert" hidden></pre><div id="conflict-actions" hidden><button id="use-outside">Use outside version</button><button id="keep-draft">Keep my draft</button></div>
<main id="layout"><section id="source" aria-label="Typst source"></section><div id="divider" role="separator" aria-label="Resize source and preview"></div>
<section id="preview" aria-label="Live preview"><div id="choose-file" hidden><p id="choose-reason"></p><select id="file-picker" aria-label="Original Typst file"></select></div>'''
    + body + '</section></main><script type="module" src="main.js"></script></body></html>\n')
(root / 'vendor/NOTICE.md').write_text('''# Bundled preview renderer

Source: https://github.com/Myriad-Dreamin/tinymist (Apache-2.0).
Extracted from the installed Tinymist preview HTML (build 2026-11-03,
Typst 0.15.1). The renderer contains typst.ts/reflexo and RxJS dependencies.
The frontend retains its upstream license comments. See LICENSE-tinymist.

Local changes are generated by `scripts/vendor.py`: explicit start/stop hooks,
an Orca RPC-backed WebSocket endpoint, and removal of the VS Code message hook.
No remote scripts or CDN assets are loaded.

Original HTML SHA-256: `''' + hashlib.sha256(source.encode()).hexdigest() + '`\n')
